import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const siteRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicDir = path.join(siteRoot, "public");
const canonicalBase = "https://www.simplemanplumbing.net";
const generatedMarker = "<!-- Generated by scripts/generate-ai-discovery.mjs; do not edit by hand. -->";

const pageDescriptions = {
  "index.html": "Overview of Simple Man Plumbing, its approach, and its service-area links.",
  "services.html": "Residential plumbing services, work categories, and a clear-pricing approach.",
  "areas.html": "Service-area index with links to each represented community.",
  "about.html": "Background, working approach, and homeowner-focused commitments.",
  "contact.html": "Contact options and appointment-request information.",
  "flood-prevention-sump-pumps.html": "Flood-prevention, sump-pump, drainage, and backup-readiness guidance for Indiana homeowners.",
};

function decodeEntities(value) {
  return value
    .replace(/&nbsp;/gi, " ")
    .replace(/&middot;/gi, "·")
    .replace(/&amp;/gi, "&")
    .replace(/&quot;/gi, '"')
    .replace(/&#39;|&apos;/gi, "'")
    .replace(/&ndash;|&mdash;/gi, "-")
    .replace(/&rsquo;|&lsquo;/gi, "'")
    .replace(/&rdquo;|&ldquo;/gi, '"')
    .replace(/&#(x[0-9a-f]+|\d+);/gi, (_, code) => {
      const numeric = code.startsWith("x") ? Number.parseInt(code.slice(1), 16) : Number.parseInt(code, 10);
      return Number.isFinite(numeric) ? String.fromCodePoint(numeric) : "";
    });
}

function htmlToText(html) {
  return decodeEntities(
    html
      .replace(/<!--[\s\S]*?-->/g, "")
      .replace(/<script\b[\s\S]*?<\/script>/gi, "")
      .replace(/<style\b[\s\S]*?<\/style>/gi, "")
      .replace(/<noscript\b[\s\S]*?<\/noscript>/gi, "")
      .replace(/<br\s*\/?>/gi, "\n")
      .replace(/<\/(?:p|div|section|article|header|footer|li|h[1-6]|tr|details|summary)>/gi, "\n")
      .replace(/<[^>]+>/g, " ")
      .replace(/[ \t]+\n/g, "\n")
      .replace(/\n{3,}/g, "\n\n")
      .replace(/[ \t]{2,}/g, " ")
      .trim(),
  );
}

function pageUrl(filename) {
  return filename === "index.html" ? `${canonicalBase}/` : `${canonicalBase}/${filename}`;
}

function titleFromHtml(html, filename) {
  const title = html.match(/<title>([\s\S]*?)<\/title>/i)?.[1];
  return title ? htmlToText(title) : filename.replace(/\.html$/, "");
}

async function publicPages() {
  const entries = await readdir(publicDir);
  const pages = await Promise.all(
    entries
      .filter((entry) => entry.endsWith(".html") && entry !== "404.html")
      .sort((a, b) => (a === "index.html" ? -1 : b === "index.html" ? 1 : a.localeCompare(b)))
      .map(async (filename) => {
        const html = await readFile(path.join(publicDir, filename), "utf8");
        if (/<meta\s+[^>]*name=["']robots["'][^>]*content=["'][^"']*noindex/i.test(html)) {
          return null;
        }
        return { filename, title: titleFromHtml(html, filename), text: htmlToText(html) };
      }),
  );
  return pages.filter(Boolean);
}

function shortSummary(pages) {
  const core = pages.filter(({ filename }) => !filename.startsWith("plumber-"));
  const locations = pages.filter(({ filename }) => filename.startsWith("plumber-"));
  const lines = [
    generatedMarker,
    "# Simple Man Plumbing",
    "",
    "> Residential plumbing for Indianapolis and the Northside, including repair, water-heater, sump-pump, drainage, and home-system work. This reference follows the public demo’s stated services and service areas; an on-site discussion determines the scope of a specific job.",
    "",
    "## Contact",
    "",
    "- Phone: +1-765-860-8667",
    "- Email: sales@simplemanplumbing.net",
    `- Website: ${canonicalBase}/`,
    "",
    "## Core pages",
    "",
    ...core.map(({ filename, title }) => `- [${title}](${pageUrl(filename)}) — ${pageDescriptions[filename] ?? "Public site page."}`),
    "",
    "## Service-area pages",
    "",
    ...locations.map(({ filename, title }) => `- [${title}](${pageUrl(filename)}) — Local service-area information.`),
    "",
    "## Use and scope",
    "",
    "Use the linked page that directly addresses the question. Service areas describe where the business may work; they do not assert a branch office in each community. For a diagnosis, schedule, emergency availability, price, permit requirement, or property-specific recommendation, contact the business directly.",
    "",
  ];
  return lines.join("\n");
}

function fullSummary(pages) {
  const lines = [
    generatedMarker,
    "# Simple Man Plumbing — full public-site reference",
    "",
    "> This file is generated from the initially delivered HTML of every public page. It is a retrieval aid, not an estimate, booking confirmation, or property-specific diagnosis.",
    "",
  ];
  for (const { filename, title, text } of pages) {
    lines.push(`## ${title}`, "", `Canonical page: ${pageUrl(filename)}`, "", text, "");
  }
  return lines.join("\n");
}

const pages = await publicPages();
await Promise.all([
  writeFile(path.join(publicDir, "llms.txt"), shortSummary(pages)),
  writeFile(path.join(publicDir, "llms-full.txt"), fullSummary(pages)),
]);

console.log(`Generated AI discovery documents from ${pages.length} public pages.`);
