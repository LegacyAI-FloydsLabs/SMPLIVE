const publicDirectory = fileURLToPath(new URL("../public/", import.meta.url));
const canonicalOrigin = "https://www.simplemanplumbing.net";

function escapeForRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function readMetaContent(html, attribute, value) {
  const tag = new RegExp(
    `<meta\\s+[^>]*${attribute}=["']${escapeForRegex(value)}["'][^>]*>`,
    "i",
  ).exec(html)?.[0];
  const content = tag && /content=(["'])([\s\S]*?)\1/i.exec(tag)?.[2];
  return content?.replace(/&mdash;/g, "—") ?? "";
}

function normalizeText(value) {
  return value
    .replace(/&amp;/gi, "&")
    .replace(/&mdash;/gi, "—")
    .replace(/&ndash;/gi, "–")
    .replace(/&middot;/gi, "·")
    .replace(/&quot;/gi, '"')
    .replace(/&#39;|&apos;/gi, "'")
    .replace(/&rsquo;|&lsquo;/gi, "'")
    .replace(/\s+/g, " ")
    .trim();
}

function isNoindex(html) {
  return /<meta\s+[^>]*name=["']robots["'][^>]*content=["'][^"']*noindex/i.test(html);
}

function visibleText(html) {
  return html
    .replace(/<!--([\s\S]*?)-->/g, "")
    .replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, "")
    .replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi, "")
    .replace(/<[^>]+>/g, " ")
    .replace(/&(?:nbsp|mdash|ndash);/gi, " ")
    .replace(/\s+/g, " ");
}

function jsonLdObjects(html) {
  return [...html.matchAll(/<script\s+type=["']application\/ld\+json["'][^>]*>([\s\S]*?)<\/script>/gi)]
    .map((match) => JSON.parse(match[1]));
}

function graphNodes(html) {
  return jsonLdObjects(html).flatMap((item) => item["@graph"] ?? [item]);
}

function includesType(node, expected) {
  return (Array.isArray(node["@type"]) ? node["@type"] : [node["@type"]]).includes(expected);
}

function sitemapLocations(xml) {
  return [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map((match) => match[1].trim());
}

function detailsFaqs(html) {
  return [...html.matchAll(/<details\b[^>]*>\s*<summary[^>]*>([\s\S]*?)<\/summary>\s*<div[^>]*>([\s\S]*?)<\/div>\s*<\/details>/gi)]
    .map((match) => ({ question: normalizeText(match[1].replace(/<[^>]+>/g, " ")), answer: normalizeText(match[2].replace(/<[^>]+>/g, " ")) }))
    .filter(({ question, answer }) => question && answer);
}

test("publishes crawlability resources that agree on the canonical site", async () => {
  const [robots, sitemap, llms, fullReference] = await Promise.all([
    readFile(path.join(publicDirectory, "robots.txt"), "utf8"),
    readFile(path.join(publicDirectory, "sitemap.xml"), "utf8"),
    readFile(path.join(publicDirectory, "llms.txt"), "utf8"),
    readFile(path.join(publicDirectory, "llms-full.txt"), "utf8"),
  ]);

  assert.match(robots, /^User-agent:\s*\*/mi);
  assert.match(robots, /^Allow:\s*\/\s*$/mi);
  assert.match(robots, new RegExp(`^Sitemap:\\s*${escapeForRegex(canonicalOrigin)}/sitemap\\.xml\\s*$`, "mi"));
  assert.match(robots, /Allow:\s*\/llms\.txt/i);
  assert.match(sitemap, /<urlset\b[^>]*sitemaps\.org\/schemas\/sitemap\/0\.9/i);
  assert.match(llms, /^# Simple Man Plumbing\s*$/m);
  assert.match(llms, new RegExp(escapeForRegex(canonicalOrigin)));
  assert.match(fullReference, /Generated by scripts\/generate-ai-discovery\.mjs/);
  assert.match(fullReference, /Canonical page: https:\/\/www\.simplemanplumbing\.net\/flood-prevention-sump-pumps\.html/);

  for (const userAgent of ["GPTBot", "OAI-SearchBot", "ChatGPT-User", "ClaudeBot", "PerplexityBot", "Google-Extended"]) {
    assert.match(robots, new RegExp(`^User-agent:\\s*${escapeForRegex(userAgent)}\\s*$`, "mi"));
  }
});

