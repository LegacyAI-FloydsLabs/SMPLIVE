test("sitemap covers every public HTML page exactly once", async () => {
  const [files, sitemap] = await Promise.all([
    readdir(publicDirectory),
    readFile(path.join(publicDirectory, "sitemap.xml"), "utf8"),
  ]);
  const indexableFiles = [];
  for (const file of files.filter((entry) => entry.endsWith(".html") && entry !== "404.html")) {
    const html = await readFile(path.join(publicDirectory, file), "utf8");
    if (!isNoindex(html)) indexableFiles.push(file);
  }
  const expectedLocations = new Set(
    indexableFiles.map((file) => (file === "index.html" ? `${canonicalOrigin}/` : `${canonicalOrigin}/${file}`)),
  );
  const locations = sitemapLocations(sitemap);

  assert.equal(new Set(locations).size, locations.length, "sitemap URLs must not be duplicated");
  assert.deepEqual(new Set(locations), expectedLocations);

  for (const location of locations) {
    assert.ok(location.startsWith(`${canonicalOrigin}/`), `${location} must use the canonical origin`);
    const pathname = new URL(location).pathname;
    const file = pathname === "/" ? "index.html" : pathname.slice(1);
    assert.ok(files.includes(file), `${location} must resolve to a public file`);
  }

  for (const file of files.filter((candidate) => candidate.endsWith(".html"))) {
    const html = await readFile(path.join(publicDirectory, file), "utf8");
    assert.doesNotMatch(html, /href=["']index\.html["']/i, `${file} must link to the canonical homepage route`);
  }

  for (const url of sitemap.matchAll(/<url>\s*<loc>[^<]+<\/loc>\s*<lastmod>([^<]+)<\/lastmod>/g)) {
    assert.match(url[1], /^\d{4}-\d{2}-\d{2}$/, "every sitemap entry must have a valid last-modified date");
  }
});

test("each location page names its represented city in content, metadata, and JSON-LD", async () => {
  const files = (await readdir(publicDirectory))
    .filter((file) => file.startsWith("plumber-") && file.endsWith(".html"))
    .sort();

  assert.ok(files.length > 0, "at least one location page is required");

  for (const file of files) {
    const html = await readFile(path.join(publicDirectory, file), "utf8");
    const title = /<title>([\s\S]*?)<\/title>/i.exec(html)?.[1] ?? "";
    const city = graphNodes(html).find((node) => includesType(node, "Service"))?.areaServed?.name;

    assert.ok(city, `${file} must expose a represented city in its Service schema`);
    assert.match(title, new RegExp(escapeForRegex(city.replace("the ", "")), "i"), `${file} title must identify its represented city`);
    const searchableCity = city.replace("the ", "");
    assert.match(visibleText(html), new RegExp(`\\b${escapeForRegex(searchableCity)}\\b`, "i"), `${file} must mention ${city} in visible content`);
    assert.match(readMetaContent(html, "name", "description"), new RegExp(`\\b${escapeForRegex(searchableCity)}\\b`, "i"), `${file} description must mention ${city}`);
    assert.match(readMetaContent(html, "property", "og:title"), new RegExp(`\\b${escapeForRegex(searchableCity)}\\b`, "i"), `${file} Open Graph title must mention ${city}`);
    assert.match(readMetaContent(html, "property", "og:description"), new RegExp(`\\b${escapeForRegex(searchableCity)}\\b`, "i"), `${file} Open Graph description must mention ${city}`);

    const structuredData = graphNodes(html);
    assert.ok(
      structuredData.some(
        (item) =>
          includesType(item, "Service") &&
          item.areaServed?.["@type"] === "City" &&
          item.areaServed?.name === city,
      ),
      `${file} must expose ${city} as a Service area in the JSON-LD graph`,
    );
    assert.match(
      html,
      /href=["']flood-prevention-sump-pumps\.html["']/i,
      `${file} must connect the local page to the flood-prevention guide`,
    );
    assert.match(
      visibleText(html),
      /(?:flood|sump pump|wet basement|sewer backup)/i,
      `${file} must give local visitors a visible flood-readiness path`,
    );
  }
});

test("keeps every coverage-map pin visually distinct", async () => {
  const areas = await readFile(path.join(publicDirectory, "areas.html"), "utf8");
  const pins = [...areas.matchAll(/<g class="map-pin" data-city="([^"]+)"><circle cx="([\d.]+)" cy="([\d.]+)" r="(?:10|6)" class="pin-anchor"/g)]
    .map((match) => ({ city: match[1], x: Number(match[2]), y: Number(match[3]) }));

  assert.equal(pins.length, 11, "the coverage map must plot each service area once");
  assert.equal(new Set(pins.map((pin) => `${pin.x},${pin.y}`)).size, pins.length, "map pin coordinates must not be duplicated");
  for (const [index, pin] of pins.entries()) {
    for (const other of pins.slice(index + 1)) {
      const distance = Math.hypot(pin.x - other.x, pin.y - other.y);
      assert.ok(distance >= 30, `${pin.city} and ${other.city} pins must remain separated`);
    }
  }
  assert.equal((areas.match(/class="pin-leader"/g) ?? []).length, pins.length, "every coverage pin must have a leader line to its separate label");
});

test("uses one cross-linked JSON-LD graph and disciplined metadata on every public page", async () => {
  const files = (await readdir(publicDirectory)).filter((file) => file.endsWith(".html"));

  for (const file of files) {
    const html = await readFile(path.join(publicDirectory, file), "utf8");
    if (isNoindex(html)) continue;
    const graphs = jsonLdObjects(html);
    assert.equal(graphs.length, 1, `${file} must have one JSON-LD block`);
    assert.ok(Array.isArray(graphs[0]["@graph"]), `${file} JSON-LD must use @graph`);
    assert.ok(graphNodes(html).some((node) => includesType(node, "WebSite")), `${file} must describe the website`);
    assert.ok(graphNodes(html).some((node) => includesType(node, "BreadcrumbList")), `${file} must include breadcrumbs`);

    const expectedCanonical = file === "index.html" ? `${canonicalOrigin}/` : `${canonicalOrigin}/${file}`;
    const canonical = /<link\s+[^>]*rel=["']canonical["'][^>]*href=["']([^"']+)["']/i.exec(html)?.[1] ?? "";
    assert.equal(canonical, expectedCanonical, `${file} must have one self-referencing canonical URL`);

    const title = normalizeText(/<title>([\s\S]*?)<\/title>/i.exec(html)?.[1] ?? "");
    assert.ok(title.length > 0 && title.length <= 60, `${file} title must be present and 60 characters or fewer`);
    assert.equal((title.match(/Simple Man Plumbing/gi) ?? []).length, 1, `${file} title must name the brand exactly once`);

    const description = normalizeText(readMetaContent(html, "name", "description"));
    assert.ok(description.length > 0 && description.length <= 155, `${file} description must be present and 155 characters or fewer`);
    assert.equal(normalizeText(readMetaContent(html, "property", "og:title")), title, `${file} Open Graph title must match the page title`);
    assert.equal(normalizeText(readMetaContent(html, "name", "twitter:title")), title, `${file} Twitter title must match the page title`);
    assert.equal(normalizeText(readMetaContent(html, "property", "og:description")), description, `${file} Open Graph description must match the page description`);
    assert.equal(normalizeText(readMetaContent(html, "name", "twitter:description")), description, `${file} Twitter description must match the page description`);

    const webPage = graphNodes(html).find((node) => includesType(node, "WebPage"));
    assert.equal(normalizeText(webPage?.name ?? ""), title, `${file} WebPage name must match the page title`);
    assert.equal(normalizeText(webPage?.description ?? ""), description, `${file} WebPage description must match the page description`);

    const organization = graphNodes(html).find((node) => includesType(node, "Organization"));
    assert.ok(!Object.hasOwn(organization ?? {}, "priceRange"), `${file} must not expose unapproved price ranges in search markup`);
    const person = graphNodes(html).find((node) => includesType(node, "Person"));
    assert.ok(Array.isArray(person?.knowsAbout) && person.knowsAbout.length > 0, `${file} must identify the named plumber's supported expertise`);
  }

  for (const file of ["index.html", "services.html", "areas.html", "about.html", "contact.html", "flood-prevention-sump-pumps.html"]) {
    const html = await readFile(path.join(publicDirectory, file), "utf8");
    const title = normalizeText(/<title>([\s\S]*?)<\/title>/i.exec(html)?.[1] ?? "");
    assert.match(title, /Indianapolis/i, `${file} must make its Indianapolis relevance explicit in the title`);
  }
});

