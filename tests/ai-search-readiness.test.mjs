test("keeps FAQ and article structured data synchronized with visible page content", async () => {
  const files = (await readdir(publicDirectory)).filter((file) => file.endsWith(".html"));

  for (const file of files) {
    const html = await readFile(path.join(publicDirectory, file), "utf8");
    const nodes = graphNodes(html);
    const faqPage = nodes.find((node) => includesType(node, "FAQPage"));
    const visibleFaqs = detailsFaqs(html);
    if (faqPage) {
      const structuredFaqs = (faqPage.mainEntity ?? []).map((entry) => ({
        question: normalizeText(entry.name ?? ""),
        answer: normalizeText(entry.acceptedAnswer?.text ?? ""),
      }));
      assert.deepEqual(structuredFaqs, visibleFaqs, `${file} FAQ schema must exactly match its visible details`);
    } else {
      assert.equal(visibleFaqs.length, 0, `${file} must not show a FAQ block without matching FAQ schema`);
    }

    for (const image of html.matchAll(/<img\b[^>]*>/gi)) {
      assert.match(image[0], /\balt=["'][^"']+["]/, `${file} images must have descriptive alt text`);
    }
  }

  const floodHtml = await readFile(path.join(publicDirectory, "flood-prevention-sump-pumps.html"), "utf8");
  const article = graphNodes(floodHtml).find((node) => includesType(node, "BlogPosting"));
  assert.ok(article, "the flood guide must retain article schema");
  const visibleHeadline = normalizeText(/<h1\b[^>]*>([\s\S]*?)<\/h1>/i.exec(floodHtml)?.[1]?.replace(/<[^>]+>/g, " ") ?? "");
  assert.equal(normalizeText(article.headline), visibleHeadline, "article headline must be visible as the H1");
  assert.equal(normalizeText(article.description), normalizeText(readMetaContent(floodHtml, "name", "description")), "article description must match the page description");
  assert.match(article.wordCount, /^\d+$/, "article word count must be numeric");
});
